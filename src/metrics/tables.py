"""Build, write and read the metrics tables (FR-013; data-model.md).

Writing goes to a temporary folder next to ``data/metrics`` and is swapped in at the end, so an
interruption never leaves half the tables. The CSV format is fixed (column order, 4 decimals, empty
cell for a missing value), so the same inputs always give the same bytes.
"""

import hashlib
import json
import shutil
from pathlib import Path

import pandas as pd

from metrics import config, cost, iic, primary, sources, stats

METRICS_COLUMNS = ("set", "scenario", "cut", "cut_value", *primary.COLUMNS[2:])


def _metrics_with_cuts(per_problem: pd.DataFrame) -> pd.DataFrame:
    blocks = [primary.table(per_problem).assign(cut="all", cut_value="")]
    for column, cut in (("macrocategoria", "macrocategoria"), ("status", "status")):
        for value in sorted(v for v in set(per_problem[column]) if v):
            part = per_problem[per_problem[column] == value]
            if part["problem"].nunique() < 2:
                continue
            blocks.append(primary.table(part).assign(cut=cut, cut_value=value))
    return pd.concat(blocks, ignore_index=True)[list(METRICS_COLUMNS)]


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest() if Path(path).is_file() else ""


def run_info(root: Path) -> dict:
    root = Path(root)
    return {
        "schema_version": 1,
        "alpha": config.ALPHA,
        "dataset_manifest_sha256": _sha256(root / config.DATASET_MANIFEST),
        "evaluation_manifests": {
            s: _sha256(root / config.evaluation_manifest(s)) for s in config.SETS
        },
        "generation_reports": {
            m: _sha256(root / config.generation_report(m)) for m in config.MODELS
        },
    }


def build(root: Path = Path("."), evaluation_dir: Path = config.EVALUATION_DIR) -> dict:
    per_problem, detected_wa = sources.load(root, evaluation_dir)
    return {
        "per_problem": per_problem,
        "detected_wa": detected_wa,
        "metrics": _metrics_with_cuts(per_problem),
        "iic": iic.table(detected_wa, per_problem),
        "stats": stats.table(per_problem),
        "cost": cost.table(root, per_problem),
    }


FLOAT_FORMAT = {"cost": "%.8f", "stats": "%.6f"}  # US$ per detection is ~1e-4; p-values need 6


def to_csv(frame: pd.DataFrame, name: str = "") -> str:
    fmt = FLOAT_FORMAT.get(name, f"%.{config.DECIMALS}f")
    return frame.to_csv(index=False, float_format=fmt, lineterminator="\n")


def write(root: Path, tables: dict, info: dict, target: Path | None = None) -> Path:
    target = Path(root) / (target or config.METRICS_DIR)
    tmp = target.with_name(target.name + ".tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    for name, file_name in config.TABLES.items():
        (tmp / file_name).write_text(to_csv(tables[name], name), encoding="utf-8")
    (tmp / config.RUN_FILE).write_text(
        json.dumps(info, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    figures = target / "figures"
    if figures.is_dir():  # figures are regenerated by `figures`; keep them across a recompute
        shutil.copytree(figures, tmp / "figures")
    if target.exists():
        shutil.rmtree(target)
    tmp.rename(target)
    return target


EXPECTED = {
    "per_problem": sources.PER_PROBLEM_COLUMNS,
    "detected_wa": sources.DETECTED_COLUMNS,
    "metrics": METRICS_COLUMNS,
    "iic": iic.COLUMNS,
    "stats": stats.COLUMNS,
    "cost": cost.COLUMNS,
}


def read(root: Path = Path("."), folder: Path | None = None) -> dict:
    """The tables of ``data/metrics``, validated against the fixed columns."""
    folder = Path(root) / (folder or config.METRICS_DIR)
    out = {}
    for name, file_name in config.TABLES.items():
        frame = pd.read_csv(folder / file_name, keep_default_na=True, dtype={"cut_value": str})
        if tuple(frame.columns) != tuple(EXPECTED[name]):
            raise ValueError(f"{file_name}: columns differ from the expected schema")
        out[name] = frame
    for column in ("has_suite", "ac_rejected"):
        out["per_problem"][column] = out["per_problem"][column].astype(bool)
    for column in ("macrocategoria", "status"):
        out["per_problem"][column] = out["per_problem"][column].fillna("")
    out["metrics"]["cut_value"] = out["metrics"]["cut_value"].fillna("")
    return out
