"""The execution phase of one attempt: the Python solution, judged and run in the engine sandbox.

The solution generated by the model (``reference_py``) is first run on every public test of the
problem, in the order of ``testes.json``; the first one that is not AC fails the attempt
(``public_test_failed``) and no generated input runs. Otherwise it runs on each generated input:
the real ``stdout`` is the expected output of that test, never normalized. An input that times out,
crashes or prints invalid UTF-8 is dropped alone; if none survives the attempt fails
(``all_inputs_failed``). ``AC_ref.cpp`` plays no part here (it is not even read).

Every run goes through the engine (``sandbox.runner.execute``) as the slot uid, without network,
in a fresh workdir, and every verdict comes from ``sandbox.judge.judge_test``. The limits are the
limits of the problem times ``PY_TIME_FACTOR`` and ``PY_MEMORY_FACTOR``; nothing is absolute.
Nothing of ``src/sandbox/`` changes. An ``InfraError`` of the engine propagates: a broken
environment is never a verdict nor a failed attempt.
"""

import sys
from collections.abc import Callable
from pathlib import Path

from ai_clients import config
from ai_clients.problem import JudgeInput, ProblemInput
from ai_clients.schemas.common import AttemptFailure, InputDiscard
from ai_clients.schemas.execution import (
    EffectiveLimits,
    ExecutionRecord,
    InputOutcome,
    PublicTestsSummary,
)
from ai_clients.schemas.generation import GenerationRecord
from dataset.schemas.metadata import Metadata
from sandbox import isolation
from sandbox import runner as engine
from sandbox.judge import judge_test
from sandbox.limits import wall_reserve_seconds
from sandbox.types import ExecutionLimits, InfraError, RunResult, Verdict

PythonRunner = Callable[
    [str, bytes, ExecutionLimits, int], RunResult
]  # (code, stdin, limits, slot)

SOURCE_NAME = "main.py"


def interpreter_path() -> Path:
    """The base CPython of the image, not the one of the venv: only the standard library exists."""
    return (
        Path(sys.base_prefix) / "bin" / f"python{sys.version_info.major}.{sys.version_info.minor}"
    )


def interpreter() -> str:
    """Path and version of the interpreter, as recorded in every execution record."""
    return f"{interpreter_path()} (CPython {sys.version.split()[0]})"


def _encode(text: str) -> bytes:
    # `surrogatepass` keeps an unpaired surrogate of the model's answer as it is; the interpreter
    # then rejects the source (a runtime error), instead of this process crashing.
    return text.encode("utf-8", errors="surrogatepass")


def run_python(code: str, stdin: bytes, limits: ExecutionLimits, slot: int) -> RunResult:
    """Run ``code`` on ``stdin`` in a fresh workdir of ``slot``, as the slot uid.

    ``-I`` ignores every ``PYTHON*`` variable and the user directory, ``-S`` skips ``site``, ``-B``
    writes no ``.pyc``, and ``-X utf8`` makes the standard streams UTF-8 (``-I`` also ignores
    ``PYTHONIOENCODING``).
    """
    workdir = isolation.prepare_slot_workdir(slot)
    source = workdir / SOURCE_NAME
    try:
        source.write_bytes(_encode(code))
    except OSError as exc:
        raise InfraError(f"cannot write {source}: {exc}") from exc
    isolation.give_to_slot(source, slot)
    return engine.execute(
        [str(interpreter_path()), "-I", "-S", "-B", "-X", "utf8", SOURCE_NAME],
        stdin=stdin,
        slot=slot,
        rlimits=isolation.run_rlimits(limits),
        cwd=workdir,
        wall_limit_s=wall_reserve_seconds(limits.time_limit_seconds),
        env={},
        measured_by_launcher=True,
    )


def python_limits(metadata: Metadata) -> ExecutionLimits:
    """The limits of the problem times the factors of the design."""
    return ExecutionLimits(
        time_limit_seconds=metadata.time_limit_seconds * config.PY_TIME_FACTOR,
        memory_limit_bytes=metadata.memory_limit_bytes * config.PY_MEMORY_FACTOR,
    )


def _input_outcome(index: int, run: RunResult, limits: ExecutionLimits) -> InputOutcome:
    # Nothing is expected yet (this run is what defines it), so only TLE, MLE and RE matter here.
    verdict = judge_test(run, "", limits)
    output, discard = None, None
    if verdict is Verdict.TLE:
        discard = InputDiscard.TIMEOUT
    elif verdict in (Verdict.MLE, Verdict.RE):
        discard = InputDiscard.RUNTIME_ERROR
    else:
        verdict = None
        try:
            output = run.stdout.decode("utf-8")
        except UnicodeDecodeError:
            discard = InputDiscard.NON_UTF8_OUTPUT
    return InputOutcome(
        index=index,
        kept=discard is None,
        output=output,
        discard=discard,
        verdict=verdict,
        cpu_time_s=run.cpu_time_s,
        peak_rss_bytes=run.peak_rss_bytes,
        stderr_tail="" if discard is None else run.stderr_tail.decode("utf-8", errors="replace"),
    )


def evaluate_attempt(
    generation: GenerationRecord,
    problem: JudgeInput | ProblemInput,
    *,
    slot: int = 0,
    runner: PythonRunner = run_python,
) -> ExecutionRecord:
    """Judge the solution of a parsed attempt on the public tests, then run it on every input."""
    if not generation.parse.ok:
        raise ValueError("only a parsed attempt has a solution to execute")
    code = generation.parse.reference_py
    limits = python_limits(problem.metadata)
    public = problem.testes.public_tests
    failed_index, failed_verdict = None, None
    for index, test in enumerate(public):
        run = runner(code, _encode(test.input), limits, slot)
        verdict = judge_test(run, test.output, limits)
        if verdict is not Verdict.AC:
            failed_index, failed_verdict = index, verdict
            break
    inputs = []
    if failed_index is None:
        for index, text in enumerate(generation.parse.inputs):
            run = runner(code, _encode(text), limits, slot)
            inputs.append(_input_outcome(index, run, limits))
    if failed_index is not None:
        outcome = AttemptFailure.PUBLIC_TEST_FAILED
    elif not any(item.kept for item in inputs):
        outcome = AttemptFailure.ALL_INPUTS_FAILED
    else:
        outcome = "accepted"
    return ExecutionRecord(
        problem_id=generation.problem_id,
        scenario=generation.scenario,
        attempt=generation.attempt,
        limits=EffectiveLimits(
            time_limit_seconds=limits.time_limit_seconds,
            memory_limit_bytes=limits.memory_limit_bytes,
            problem_time_limit_seconds=problem.metadata.time_limit_seconds,
            problem_memory_limit_bytes=problem.metadata.memory_limit_bytes,
        ),
        interpreter=interpreter(),
        public_tests=PublicTestsSummary(
            total=len(public),
            passed=len(public) if failed_index is None else failed_index,
            failed_index=failed_index,
            failed_verdict=failed_verdict,
        ),
        inputs=inputs,
        outcome=outcome,
    )
