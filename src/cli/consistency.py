SLM_SCENARIOS = ("black_box", "white_box", "hybrid")
SLM_MAX_ATTEMPTS = 15  # ai_clients.config.MAX_ATTEMPTS
SLM_SOLUTION_ATTEMPTS = 12  # ai_clients.config.SOLUTION_ATTEMPTS: later ones are never executed
SLM_ATTEMPT_FILE = re.compile(r"^attempt_(\d+)\.(generation|execution)\.json$")
SLM_OTHER_FILES = {"suite.json", "manual_close.json"}


def _slm_attempt_lines(
    root: Path, layer: Layer, problems: dict[str, set[str]], in_progress: bool
) -> list[Line]:
    """Inside each scenario: only ``suite.json``, ``manual_close.json`` and attempt files,
    numbered 1..k with k <= 15, executions only up to the 12th."""
    base = root / layer.root
    scenarios = gaps = without_suite = 0
    broken, suites_missing, strange = [], [], []
    for problem_id in sorted(problems):
        for scenario in SLM_SCENARIOS:
            folder = base / problem_id / scenario
            if not folder.is_dir():
                continue
            scenarios += 1
            names = {p.name for p in folder.iterdir() if not p.name.startswith(".")}
            generations, executions = set(), set()
            for name in sorted(names - SLM_OTHER_FILES):
                match = SLM_ATTEMPT_FILE.match(name)
                if match is None:
                    strange.append(f"{problem_id}/{scenario}: {name}")
                    continue
                (generations if match[2] == "generation" else executions).add(int(match[1]))
            last = max(generations | executions, default=0)
            if (
                last > SLM_MAX_ATTEMPTS
                or generations != set(range(1, last + 1))
                or any(n > SLM_SOLUTION_ATTEMPTS for n in executions)
            ):
                gaps += 1
                broken.append(f"{problem_id}/{scenario}")
            if "suite.json" not in names:
                without_suite += 1
                suites_missing.append(f"{problem_id}/{scenario}")
    lines = [
        Line(
            OK if not broken else FAIL,
            f"tentativas numeradas sem buraco, no máximo {SLM_MAX_ATTEMPTS} (execuções até a "
            f"{SLM_SOLUTION_ATTEMPTS}ª): "
            f"{scenarios - gaps}/{scenarios}",
            _listed(broken),
        ),
        Line(
            OK if not suites_missing else (WARN if in_progress else FAIL),
            f"suite.json em cada cenário: {scenarios - without_suite}/{scenarios}",
            _listed(suites_missing),
        ),
    ]
    if strange:
        lines.append(
            Line(FAIL, f"{len(strange)} arquivo(s) estranho(s) num cenário", _listed(strange))
        )
    return lines


SLM_DIR = Path("data/suites/slm")
SLM_CHANGES_DIR = "template_changes"  # ai_clients.config.TEMPLATE_CHANGES_DIR
SLM_SUPERSEDED_DIR = "superseded"  # ai_clients.config.SUPERSEDED_DIR


def _slm_superseded_lines(root: Path) -> list[Line]:
    """The attempts a template change moved aside (``superseded/<NNN>/``, ai_clients R27): each
    file a change lists is there and no longer in ``problems/``, and nothing else is there."""
    base = root / SLM_DIR
    changes, kept = base / SLM_CHANGES_DIR, base / SLM_SUPERSEDED_DIR
    if not changes.is_dir() and not kept.is_dir():
        return []
    names = []
    if changes.is_dir():
        names = sorted(p.name for p in changes.iterdir() if not p.name.startswith("."))
    listed: set[str] = set()
    wrong: list[str] = []
    combinations = 0
    for number, name in enumerate(names, start=1):
        if name != f"{number:03d}.json":
            wrong.append(f"{SLM_CHANGES_DIR}/{name}: fora da sequência 001.json, 002.json, ...")
            continue
        try:
            change = json.loads((changes / name).read_text(encoding="utf-8"))
            items = [
                (i["problem_id"], i["scenario"], list(i["files"])) for i in change["superseded"]
            ]
        except (OSError, ValueError, KeyError, TypeError):
            wrong.append(f"{SLM_CHANGES_DIR}/{name}: não é um registro de troca")
            continue
        for problem_id, scenario, files in items:
            combinations += 1
            for file in files:
                rel = f"{name.removesuffix('.json')}/{problem_id}/{scenario}/{file}"
                listed.add(rel)
                if (kept / rel).is_file():
                    continue  # a file of the same name in problems/ is the one made again
                if (base / "problems" / problem_id / scenario / file).exists():
                    wrong.append(f"{rel}: ainda não movido (rode o mesmo change-template de novo)")
                else:
                    wrong.append(f"{rel}: falta em {SLM_SUPERSEDED_DIR}/")
    if kept.is_dir():
        for path in sorted(kept.rglob("*")):
            rel = path.relative_to(kept).as_posix()
            hidden = any(part.startswith(".") for part in path.relative_to(kept).parts)
            if path.is_file() and not hidden and rel not in listed:
                wrong.append(f"{rel}: nenhuma troca de template o lista")
    return [
        Line(
            INFO,
            f"trocas de template: {len(names)}; combinações refeitas: {combinations}; arquivos "
            f"guardados em {SLM_SUPERSEDED_DIR}/: {len(listed)} (fora das métricas)",
        ),
        Line(
            OK if not wrong else FAIL,
            f"{SLM_SUPERSEDED_DIR}/ bate com as trocas de template",
            _listed(wrong),
        ),
    ]


def _slm_lines(
    root: Path, layer: Layer, problems: dict[str, set[str]], in_progress: bool
) -> list[Line]:
    return _slm_attempt_lines(root, layer, problems, in_progress) + _slm_superseded_lines(root)


