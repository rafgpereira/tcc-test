"""Consistency of the artifacts of the pipeline (structure, not content): the library of ``python -m cli check``.

Walks the real folders (the EXTRACTED dataset, ``data/dataset/``, and the mutants,
``data/mutants/``) and answers, with counts, the questions that are hard to trust by eye:

* the dataset has exactly the number of problems its manifest says, and each problem folder has
  every file it must have (``AC_ref.cpp``, ``enunciado.md``, ``metadata.json``, ``testes.json``,
  ``validacao.json`` and ``WA_1.cpp`` to ``WA_100.cpp``) and nothing else;
* each problem has its ``Mutant_1.cpp`` to ``Mutant_100.cpp`` and nothing else;
* dataset and mutants are 1:1: no problem without mutants, no mutants without a problem;
* the names of the files on disk are the names the manifests list (missing and extra files).

It never reads the code inside the files and never writes anything. ``deep=True`` additionally
recomputes the SHA-256 of every file and of the zips and compares them with the manifests, for the
moment right before an experiment consumes the data.

New artifacts of later modules (for example the tests generated by the AIs) are added as one more
``Layer`` in ``LAYERS`` below; see ``docs/verificacao-consistencia.md``.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

WA_PER_PROBLEM = 100
MUTANTS_PER_PROBLEM = 100
PROBLEM_ID = re.compile(r"^\d+_[A-Za-z0-9]+$")
MAX_LISTED = 10  # ids listed under a failing line; the rest is summarized as "... and N more"

OK, FAIL, WARN, INFO = "OK", "FALHA", "AVISO", "INFO"


@dataclass(frozen=True)
class Group:
    """A set of file names that every problem folder of a layer must contain, all of them."""

    label: str
    names: frozenset[str]


@dataclass(frozen=True)
class Layer:
    """One kind of artifact laid out as ``<root>/<problem_id>/<files>``, one folder per problem."""

    key: str  # value of --only
    title: str
    root: str  # folder that holds the problem folders, relative to the repository
    groups: tuple[Group, ...]
    allowed_extra: frozenset[str]  # names that may sit in a problem folder besides the groups
    manifest: str | None  # manifest of the layer, relative to the repository
    manifest_required: bool
    manifest_prefix: str  # path prefix of the layer's files inside its manifest
    zip_path: str | None = None  # the packaged zip, checked (only with --deep) against the manifest
    zip_key: str | None = None  # key of the zip entry in the manifest
    compared_names: frozenset[str] | None = None  # None: every name; else only these are compared


DATASET_LAYER = Layer(
    key="dataset",
    title="Dataset (data/dataset/problems)",
    root="data/dataset/problems",
    groups=(
        Group("AC_ref.cpp", frozenset({"AC_ref.cpp"})),
        Group("enunciado.md", frozenset({"enunciado.md"})),
        Group("metadata.json", frozenset({"metadata.json"})),
        Group("testes.json", frozenset({"testes.json"})),
        Group("validacao.json", frozenset({"validacao.json"})),
        Group(
            f"WA_1.cpp a WA_{WA_PER_PROBLEM}.cpp",
            frozenset(f"WA_{i}.cpp" for i in range(1, WA_PER_PROBLEM + 1)),
        ),
    ),
    allowed_extra=frozenset(),
    manifest="manifests/dataset.manifest.json",
    manifest_required=True,
    manifest_prefix="dataset/problems/",
    zip_path="data/dataset.zip",
    zip_key="dataset_zip",
)

MUTANTS_LAYER = Layer(
    key="mutants",
    title="Mutantes (data/mutants/problems)",
    root="data/mutants/problems",
    groups=(
        Group(
            f"Mutant_1.cpp a Mutant_{MUTANTS_PER_PROBLEM}.cpp",
            frozenset(f"Mutant_{i}.cpp" for i in range(1, MUTANTS_PER_PROBLEM + 1)),
        ),
    ),
    allowed_extra=frozenset({"generation.json"}),  # the record of how they were generated
    manifest="manifests/mutants.manifest.json",
    manifest_required=False,  # it only exists after `mutation package`
    manifest_prefix="mutants/problems/",
    zip_path="data/mutants.zip",
    zip_key="mutants_zip",
    compared_names=frozenset(f"Mutant_{i}.cpp" for i in range(1, MUTANTS_PER_PROBLEM + 1)),
)

# The first layer is the reference: every other layer must be 1:1 with it. A later module adds its
# own Layer here (for example the tests generated by the AIs) and the relation check covers it.
LAYERS: tuple[Layer, ...] = (DATASET_LAYER, MUTANTS_LAYER)


# ---------------------------------------------------------------------------------------- report


@dataclass
class Line:
    status: str
    text: str
    details: list[str] = field(default_factory=list)


@dataclass
class Section:
    title: str
    lines: list[Line] = field(default_factory=list)

    def add(self, status: str, text: str, details: list[str] | None = None) -> None:
        self.lines.append(Line(status, text, details or []))


@dataclass
class Report:
    sections: list[Section] = field(default_factory=list)

    @property
    def failures(self) -> int:
        return sum(1 for s in self.sections for l in s.lines if l.status == FAIL)

    @property
    def warnings(self) -> int:
        return sum(1 for s in self.sections for l in s.lines if l.status == WARN)

    @property
    def ok(self) -> bool:
        return self.failures == 0

    def render(self) -> str:
        out: list[str] = []
        for section in self.sections:
            out.append(f"\n== {section.title} ==")
            for line in section.lines:
                out.append(f"[{line.status:<5}] {line.text}")
                out += [f"          {detail}" for detail in line.details]
        verdict = "OK" if self.ok else "FALHA"
        out.append(f"\nResultado: {verdict} ({self.failures} falha(s), {self.warnings} aviso(s))")
        return "\n".join(out)


def _listed(items: list[str]) -> list[str]:
    shown = sorted(items)[:MAX_LISTED]
    more = len(items) - len(shown)
    return [", ".join(shown) + (f" ... e mais {more}" if more > 0 else "")] if shown else []


# --------------------------------------------------------------------------------------- reading


def _sha256_of_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _problem_folders(root: Path) -> tuple[dict[str, set[str]], list[str]]:
    """``{problem_id: {file names}}`` and the entries that are not a well-named problem folder."""
    problems: dict[str, set[str]] = {}
    strange: list[str] = []
    for entry in sorted(root.iterdir()):
        if entry.name.startswith("."):
            continue
        if not entry.is_dir() or not PROBLEM_ID.match(entry.name):
            strange.append(entry.name)
            continue
        problems[entry.name] = {p.name for p in entry.iterdir() if not p.name.startswith(".")}
    return problems, strange


def _load_manifest(root: Path, layer: Layer) -> dict | None:
    if layer.manifest is None or not (root / layer.manifest).is_file():
        return None
    return json.loads((root / layer.manifest).read_text(encoding="utf-8"))


def _is_excluded(root: Path, layer: Layer, problem_id: str) -> bool:
    record = root / layer.root / problem_id / "generation.json"
    try:
        return json.loads(record.read_text(encoding="utf-8")).get("status") == "excluded"
    except (OSError, ValueError):
        return False


# ---------------------------------------------------------------------------------- layer checks


def check_layer(root: Path, layer: Layer, deep: bool) -> tuple[Section, dict[str, set[str]] | None]:
    """The structure of one layer; also returns its ``{problem_id: names}`` for the relation check."""
    section = Section(layer.title)
    folder = root / layer.root
    if not folder.is_dir():
        section.add(FAIL, f"a pasta {layer.root} não existe")
        return section, None
    problems, strange = _problem_folders(folder)
    manifest = _load_manifest(root, layer)
    total = len(problems)

    if manifest is not None and "problem_count" in manifest:
        expected = manifest["problem_count"]
        status = OK if total == expected else FAIL
        section.add(status, f"pastas de problema: {total} (o manifesto diz {expected})")
    else:
        section.add(INFO, f"pastas de problema: {total}")
    if strange:
        section.add(
            FAIL, f"{len(strange)} entrada(s) que não é pasta de problema", _listed(strange)
        )
    if total == 0:
        section.add(FAIL, "nenhum problema encontrado")
        return section, problems

    excluded = sorted(p for p in problems if _is_excluded(root, layer, p))
    checked = {p: n for p, n in problems.items() if p not in excluded}
    for group in layer.groups:
        broken = sorted(p for p, names in checked.items() if not group.names <= names)
        good = len(checked) - len(broken)
        status = OK if not broken else FAIL
        detail = []
        if broken:
            detail = _listed(broken)
        section.add(status, f"{group.label}: {good}/{len(checked)}", detail)
    known = set().union(*(g.names for g in layer.groups)) | layer.allowed_extra
    unexpected = sorted(p for p, names in checked.items() if names - known)
    what = [f"{p}: {', '.join(sorted(problems[p] - known)[:3])}" for p in unexpected]
    section.add(
        OK if not unexpected else FAIL,
        f"nenhum arquivo além dos esperados: {len(checked) - len(unexpected)}/{len(checked)}",
        _listed(what),
    )
    if excluded:
        section.add(
            WARN,
            f"{len(excluded)} problema(s) excluído(s) por não alcançar {MUTANTS_PER_PROBLEM} "
            "mutantes (previsto pela especificação; sem mutantes)",
            _listed(excluded),
        )
    if layer.key == "mutants":
        pending = folder.parent / "building"
        left = sorted(p.name for p in pending.iterdir()) if pending.is_dir() else []
        section.add(
            OK if not left else FAIL,
            (
                "nenhum problema pela metade em data/mutants/building"
                if not left
                else f"{len(left)} problema(s) pela metade em data/mutants/building (rode generate)"
            ),
            _listed(left),
        )
    section.lines.extend(_manifest_lines(root, layer, problems, manifest, deep))
    return section, problems


def _tree_names(layer: Layer, problems: dict[str, set[str]]) -> set[str]:
    names = set()
    for problem_id, files in problems.items():
        for name in files:
            if layer.compared_names is None or name in layer.compared_names:
                names.add(f"{layer.manifest_prefix}{problem_id}/{name}")
    return names


def _manifest_lines(
    root: Path, layer: Layer, problems: dict[str, set[str]], manifest: dict | None, deep: bool
) -> list[Line]:
    if manifest is None:
        if layer.manifest_required:
            return [Line(FAIL, f"o manifesto {layer.manifest} não existe")]
        return [
            Line(
                WARN, f"{layer.manifest} ainda não existe (pacote não gerado): nomes não conferidos"
            )
        ]
    listed = {item["path"] for item in manifest["files"]}
    on_disk = _tree_names(layer, problems)
    missing, extra = sorted(listed - on_disk), sorted(on_disk - listed)
    lines = []
    if not missing and not extra:
        lines.append(Line(OK, f"nomes dos arquivos batem com o manifesto ({len(listed)} arquivos)"))
    else:
        details = []
        if missing:
            details.append(f"faltam no disco ({len(missing)}): " + _listed(missing)[0])
        if extra:
            details.append(f"sobram no disco ({len(extra)}): " + _listed(extra)[0])
        lines.append(Line(FAIL, "nomes dos arquivos NÃO batem com o manifesto", details))
    if deep:
        lines += _deep_lines(root, layer, manifest, missing_names=set(missing))
    return lines


def _deep_lines(root: Path, layer: Layer, manifest: dict, missing_names: set[str]) -> list[Line]:
    """Recompute the SHA-256 of every file the manifest lists (and of the zip) and compare."""
    base = root / layer.root
    changed = []
    checked = 0
    for item in manifest["files"]:
        if item["path"] in missing_names:
            continue
        relative = item["path"].removeprefix(layer.manifest_prefix)
        path = base / relative
        checked += 1
        if (
            not path.is_file()
            or path.stat().st_size != item["size"]
            or _sha256_of_file(path) != item["sha256"]
        ):
            changed.append(item["path"])
    lines = [
        Line(
            OK if not changed else FAIL,
            (
                f"hash SHA-256 de {checked} arquivo(s) confere com o manifesto"
                if not changed
                else f"{len(changed)} arquivo(s) com conteúdo diferente do manifesto"
            ),
            _listed(changed),
        )
    ]
    if layer.zip_path and layer.zip_key:
        zip_file = root / layer.zip_path
        entry = manifest[layer.zip_key]
        if not zip_file.is_file():
            lines.append(Line(WARN, f"{layer.zip_path} não existe: hash do zip não conferido"))
        else:
            same = (
                zip_file.stat().st_size == entry["size"]
                and _sha256_of_file(zip_file) == entry["sha256"]
            )
            lines.append(
                Line(
                    OK if same else FAIL,
                    f"{layer.zip_path}: hash {'confere' if same else 'DIFERE'} com o manifesto",
                )
            )
    return lines


# --------------------------------------------------------------------------------- relation check


def check_relation(layers: list[Layer], found: dict[str, dict[str, set[str]]]) -> Section | None:
    """Every layer is 1:1 with the first one: nothing missing on either side."""
    base_layer, others = layers[0], layers[1:]
    if not others or base_layer.key not in found:
        return None
    section = Section("Relação 1:1 entre as camadas")
    base = set(found[base_layer.key])
    for layer in others:
        if layer.key not in found:
            section.add(
                FAIL, f"{layer.title}: pasta ausente, relação com {base_layer.key} não conferida"
            )
            continue
        theirs = set(found[layer.key])
        without = sorted(base - theirs)
        orphan = sorted(theirs - base)
        section.add(
            OK if not without else FAIL,
            f"todo problema de {base_layer.key} tem pasta em {layer.key}: {len(base) - len(without)}/{len(base)}",
            _listed(without),
        )
        section.add(
            OK if not orphan else FAIL,
            f"nenhuma pasta de {layer.key} sem problema em {base_layer.key}: {len(orphan)} sobrando",
            _listed(orphan),
        )
    return section


# ---------------------------------------------------------------------------------------- driver


def run_checks(root: Path, only: list[str] | None = None, deep: bool = False) -> Report:
    """Run the checks over ``root`` for the selected layers (all by default)."""
    layers = [layer for layer in LAYERS if only is None or layer.key in only]
    report = Report()
    found: dict[str, dict[str, set[str]]] = {}
    for layer in layers:
        section, problems = check_layer(Path(root), layer, deep)
        report.sections.append(section)
        if problems is not None:
            found[layer.key] = problems
    relation = check_relation(layers, found)
    if relation is not None:
        report.sections.append(relation)
    return report


def unknown_layers(only: list[str] | None) -> list[str]:
    """The names in ``only`` that are not a known layer."""
    known = {layer.key for layer in LAYERS}
    return [key for key in only or [] if key not in known]


def missing_manifest(root: Path, only: list[str] | None) -> str | None:
    """The first REQUIRED manifest of a selected layer that is not on disk, if any."""
    for layer in LAYERS:
        selected = only is None or layer.key in only
        if selected and layer.manifest_required and not (root / str(layer.manifest)).is_file():
            return layer.manifest
    return None
